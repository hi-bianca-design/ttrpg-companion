// Generates supabase/seed.sql from supabase/seed/<system>/<kind>.json.
// Every row's `data` is validated with the system module's Zod schema before any SQL is
// written; the script fails (writing nothing) if any row is invalid.
// Run: npm run db:seed
import fs from 'fs'
import path from 'path'
import { getSystem } from '../../src/systems/registry'
import type { SystemId } from '../../src/systems/types'

type SeedRow = {
  slug: string
  name: string
  summary?: string | null
  description?: string | null
  parent_slug?: string | null
  data: unknown
}

type SystemRow = { id: SystemId; name: string; version: string; license: string; attribution: string }

const ROOT = path.resolve(__dirname, '../..')
const SEED_DIR = path.join(ROOT, 'supabase/seed')
const OUT_FILE = path.join(ROOT, 'supabase/seed.sql')

const GAME_SYSTEMS: SystemRow[] = [
  {
    id: 'dnd5e-2024',
    name: 'D&D 5e (2024 SRD)',
    version: '5.2',
    license: 'CC-BY-4.0',
    attribution:
      'This work includes material from the System Reference Document 5.2 (“SRD 5.2”) by Wizards of the Coast LLC, licensed under CC-BY-4.0.',
  },
  {
    id: 'daggerheart',
    name: 'Daggerheart',
    version: '1.0',
    license: 'Darrington Press Community Gaming License',
    attribution:
      'This product includes materials from the Daggerheart System Reference Document 1.0, © Critical Role, LLC. under the terms of the Darrington Press Community Gaming (DPCGL) License.',
  },
]

const lit = (v: string | null | undefined): string => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`)

/** Orders kinds so every parentKind precedes its children (e.g. class before subclass). */
function orderKinds(kinds: string[], parentOf: (kind: string) => string | undefined): string[] {
  const ordered: string[] = []
  const visit = (kind: string, seen: Set<string>) => {
    if (ordered.includes(kind)) return
    if (seen.has(kind)) throw new Error(`Cycle in parentKind at ${kind}`)
    seen.add(kind)
    const parent = parentOf(kind)
    if (parent && kinds.includes(parent)) visit(parent, seen)
    ordered.push(kind)
  }
  for (const kind of kinds) visit(kind, new Set())
  return ordered
}

function buildSystemContent(systemId: SystemId, errors: string[]): { sql: string[]; counts: Record<string, number> } {
  const system = getSystem(systemId)
  const dir = path.join(SEED_DIR, systemId)
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
  const kinds = files.map((f) => path.basename(f, '.json'))
  for (const kind of kinds) {
    if (!system.contentKinds[kind]) errors.push(`${systemId}/${kind}.json: unknown content kind`)
  }
  const known = kinds.filter((k) => system.contentKinds[k])
  const sql: string[] = []
  const counts: Record<string, number> = {}

  for (const kind of orderKinds(known, (k) => system.contentKinds[k].parentKind)) {
    const def = system.contentKinds[kind]
    const rows = JSON.parse(fs.readFileSync(path.join(dir, `${kind}.json`), 'utf8')) as SeedRow[]
    counts[kind] = rows.length
    if (rows.length === 0) continue

    const values = rows.map((row) => {
      const parsed = def.schema.safeParse(row.data)
      if (!parsed.success) {
        errors.push(`${systemId}/${kind}/${row.slug}: ${parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; ')}`)
      }
      if (def.parentKind && !row.parent_slug) errors.push(`${systemId}/${kind}/${row.slug}: missing parent_slug`)
      const parent = def.parentKind && row.parent_slug
        ? `(select p.id from public.content p where p.system_id = ${lit(systemId)} and p.kind = ${lit(def.parentKind)} and p.slug = ${lit(row.parent_slug)} and p.owner_id is null)`
        : 'null'
      return `  (${lit(systemId)}, ${lit(kind)}, ${lit(row.name)}, ${lit(row.slug)}, ${lit(row.summary)}, ${lit(row.description)}, ${lit(JSON.stringify(row.data))}::jsonb, ${parent})`
    })

    sql.push(
      `-- ${systemId} / ${kind} (${rows.length})`,
      'insert into public.content (system_id, kind, name, slug, summary, description, data, parent_id) values',
      values.join(',\n'),
      'on conflict do nothing;',
      '',
    )
  }
  return { sql, counts }
}

function main() {
  const errors: string[] = []
  const out: string[] = [
    '-- GENERATED by scripts/seed/build-seed.ts from supabase/seed/**/*.json. Do not edit by hand.',
    '-- Regenerate with: npm run db:seed',
    '',
    'insert into public.game_systems (id, name, version, license, attribution) values',
    GAME_SYSTEMS.map((s) => `  (${lit(s.id)}, ${lit(s.name)}, ${lit(s.version)}, ${lit(s.license)}, ${lit(s.attribution)})`).join(',\n'),
    'on conflict do nothing;',
    '',
  ]

  const summary: string[] = []
  for (const s of GAME_SYSTEMS) {
    if (!fs.existsSync(path.join(SEED_DIR, s.id))) continue
    const { sql, counts } = buildSystemContent(s.id, errors)
    out.push(...sql)
    summary.push(`${s.id}: ${Object.entries(counts).map(([k, n]) => `${k} ${n}`).join(', ')}`)
  }

  if (errors.length > 0) {
    console.error(`Seed validation failed (${errors.length}):\n${errors.join('\n')}`)
    process.exit(1)
  }

  fs.writeFileSync(OUT_FILE, out.join('\n'))
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}\n${summary.join('\n')}`)
}

main()
